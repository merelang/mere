let __sf_mul_limbs = fn (a) -> fn (b) ->
  let p = vec_new () in
  let rec zeros = fn (k: int) -> if k <= 0 then () else let _ = vec_push p 0 in zeros (k - 1) in
  let _ = zeros 8 in
  let rec inner = fn (i: int) -> fn (j: int) -> fn (carry: int) ->
    if j >= 4 then vec_set p (i + 4) (vec_get p (i + 4) + carry)
    else
      let t = vec_get p (i + j) + vec_get a i * vec_get b j + carry in
      let _ = vec_set p (i + j) (bit_and t __sf_lmask) in
      inner i (j + 1) (bit_shr t __sf_lbits) in
  let rec outer = fn (i: int) ->
    if i >= 4 then () else let _ = inner i 0 0 in outer (i + 1) in
  let _ = outer 0 in
  p;

// The product, shifted down to the working format: at most 56 bits, which is
// 53 with three below for the guard, the round and the sticky.
//
// The shift is computed from the product's own width, NOT fixed. A fixed
// `P >> 49` is right for two normals -- their product is 105 or 106 bits -- and
// wrong the moment either operand is subnormal, because then the product is
// narrower and the bits below 49 are significand, not sticky. The gate found it
// as `0,1 * 2146435071,4294967295`: the high half matched the hardware and the
// low half came back zero. A tolerance would have accepted it.
let __sf_prod_limb = fn (p) -> fn (i: int) -> if i < 0 || i > 7 then 0 else vec_get p i;

let __sf_prod_bitlen = fn (p) ->
  let rec go = fn (k: int) ->
    if k < 0 then 0
    else if vec_get p k != 0 then k * 15 + __sf_l6_bitlen_limb (vec_get p k) 0
    else go (k - 1) in
  go 7;

// bits [from, from+15) of the product, which may straddle two limbs
let __sf_prod_bits15 = fn (p) -> fn (from: int) ->
  let li = from / 15 in
  let off = from - li * 15 in
  if off == 0 then __sf_prod_limb p li
  else bit_and (bit_or (bit_shr (__sf_prod_limb p li) off)
                       (bit_shl (__sf_prod_limb p (li + 1)) (15 - off))) __sf_lmask;

// is any bit below `n` set?
let __sf_prod_low_nonzero = fn (p) -> fn (n: int) ->
  let rec go = fn (i: int) ->
    if i >= n then 0
    else
      let li = i / 15 in
      let take = if n - i >= 15 then 15 else n - i in
      let v = bit_and (__sf_prod_limb p li) (bit_shl 1 take - 1) in
      if i - li * 15 == 0 && v != 0 then 1 else
      if bit_and (bit_shr (__sf_prod_limb p li) (i - li * 15)) (bit_shl 1 take - 1) != 0 then 1
      else go (i + take) in
  go 0;

let __sf_product_to_l6 = fn (p) ->
  let len = __sf_prod_bitlen p in
  let k = if len > 56 then len - 56 else 0 in
  let st = if k == 0 then 0 else __sf_prod_low_nonzero p k in
  let s = __sf_l6_of_limbs (__sf_prod_bits15 p (k + 75)) (__sf_prod_bits15 p (k + 60))
                      (__sf_prod_bits15 p (k + 45)) (__sf_prod_bits15 p (k + 30))
                      (__sf_prod_bits15 p (k + 15)) (__sf_prod_bits15 p k) in
  (s, k, st);

let __sf_mul = fn (a: Sf__rv) -> fn (b: Sf__rv) ->
  let sign = bit_xor a.sign b.sign in
  if __sf_is_snan a then __sf_quiet a
  else if __sf_is_snan b then __sf_quiet b
  else if __sf_is_nan a then a
  else if __sf_is_nan b then b
  else if __sf_is_inf a then (if __sf_is_zero b then __sf_nan else (if sign == 1 then __sf_neg_inf else __sf_inf))
  else if __sf_is_inf b then (if __sf_is_zero a then __sf_nan else (if sign == 1 then __sf_neg_inf else __sf_inf))
  else if __sf_is_zero a || __sf_is_zero b then __sf_mk sign 0 0 0 0 0
  else
    let (s, k, st) = __sf_product_to_l6 (__sf_mul_limbs (__sf_sig_limbs a) (__sf_sig_limbs b)) in
    // value = S * 2^(Ea + Eb - 2150 + k), and pack reads s as `significand<<3`
    // with value = s * 2^(e - 1078), so e = Ea + Eb + k - 1072.
    __sf_pack sign s (__sf_eff_exp a + __sf_eff_exp b + k - 1072) st;
// ---- contrib/softfloat/div.mere ----
// contrib/softfloat/div — IEEE 754 division, in integers only.
//
// Restoring long division: 56 quotient bits, one per round, which is 53 plus the
// three the rounding needs. The remainder at the end is the sticky.
//
// Both significands are normalised to exactly 53 bits FIRST, with the exponent
// paying for the shift. Without that a subnormal divisor makes the true
// quotient far wider than 56 bits and the loop, which produces exactly 56,
// would drop the top of it and hand back a small number where the answer is
// an overflow.

// (significand, effective exponent) with the significand's top bit at 52
let __sf_norm_sig = fn (a: Sf__rv) ->
  let h = if a.exp == 0 then 0 else __sf_hidden_bit in
  let s = __sf_l6_of_limbs 0 0 (a.f3 + h) a.f2 a.f1 a.f0 in
  let rec go = fn (v: L6__rv) -> fn (e: int) ->
    if __sf_l6_bitlen v >= 53 then (v, e) else go (__sf_l6_shl v 1) (e - 1) in
  go s (__sf_eff_exp a);

// floor(a * 2^56 / b), and whether anything was left over.
//
// The loop keeps `2^i * a = q * b + rem` with `rem < b`, and one subtraction
// per step can only hold that if the remainder is already below b when the
// loop starts. Both significands are normalised to 53 bits, so a/b is in
// (0.5, 2) and a CAN be the larger -- the first version began with `rem = a`
// and every quotient with a >= b came back half its true size. The pre-step
// takes that case out: the integer part is 1, and the loop's 56 shifts carry
// it to the top of the answer.
let __sf_divide = fn (a: L6__rv) -> fn (b: L6__rv) ->
  let (r0, q0) = if __sf_l6_cmp a b >= 0 then (__sf_l6_sub a b, __sf_l6_one) else (a, __sf_l6_zero) in
  let rec go = fn (i: int) -> fn (rem: L6__rv) -> fn (q: L6__rv) ->
    if i <= 0 then (q, if __sf_l6_is_zero rem then 0 else 1)
    else
      let r1 = __sf_l6_shl rem 1 in
      let q1 = __sf_l6_shl q 1 in
      if __sf_l6_cmp r1 b >= 0 then go (i - 1) (__sf_l6_sub r1 b) (__sf_l6_add q1 __sf_l6_one)
      else go (i - 1) r1 q1 in
  go 56 r0 q0;

// the normalised significand alone, for the gate's probe: `divide` takes limb
// vectors and the probe has an Sf.
let __sf_sig_limbs_l6 = fn (a: Sf__rv) -> fst (__sf_norm_sig a);

let __sf_fdiv = fn (a: Sf__rv) -> fn (b: Sf__rv) ->
  let sign = bit_xor a.sign b.sign in
  if __sf_is_snan a then __sf_quiet a
  else if __sf_is_snan b then __sf_quiet b
  else if __sf_is_nan a then a
  else if __sf_is_nan b then b
  else if __sf_is_inf a then (if __sf_is_inf b then __sf_nan else (if sign == 1 then __sf_neg_inf else __sf_inf))
  else if __sf_is_inf b then __sf_mk sign 0 0 0 0 0
  else if __sf_is_zero a then (if __sf_is_zero b then __sf_nan else __sf_mk sign 0 0 0 0 0)
  else if __sf_is_zero b then (if sign == 1 then __sf_neg_inf else __sf_inf)
  else
    let (na, ea) = __sf_norm_sig a in
    let (nb, eb) = __sf_norm_sig b in
    let (q, st) = __sf_divide na nb in
    // a/b = (A/B) * 2^(Ea - Eb) and q is A * 2^56 / B, so the value is
    // q * 2^(Ea - Eb - 56); pack reads s as `significand<<3` with value
    // s * 2^(e - 1078), so e = Ea - Eb + 1022.
    __sf_pack sign q (ea - eb + 1022) st;
// ---- contrib/softfloat/conv.mere ----
// contrib/softfloat/conv — between a double and the backend's own integer.
//
// Both directions have a rule that was measured rather than assumed:
// int -> double ROUNDS (to nearest, ties to even, so 2^53+1 becomes 2^53 and
// 2^53+3 becomes 2^53+4), and double -> int TRUNCATES toward zero (so -1.9
// becomes -1, not -2).

// The integer's magnitude with the binary point at 0, handed to `pack`, which
// does the normalisation and the rounding. pack reads its argument as
// `significand << 3` with value `s * 2^(e - 1078)`, so a plain integer m is
// `m << 3` at e = 1075.
//
// The magnitude of a negative integer is NOT `0 - n`. For the most negative
// value there is no positive counterpart, and the subtraction wraps back to
// itself: the gate caught `-4611686018427387904` coming out as a different
// double than the hardware's. `n / 2` always has one, so the magnitude is built
// from half of it, doubled in the limbs, with the odd bit put back.
let __sf_mag_limbs = fn (n: int) ->
  if n >= 0 then __sf_l6_of_int n
  else __sf_l6_add (__sf_l6_shl (__sf_l6_of_int (0 - (n / 2))) 1)
              (if bit_and n 1 == 1 then __sf_l6_one else __sf_l6_zero);

let __sf_of_int = fn (n: int) ->
  if n == 0 then __sf_zero
  else __sf_pack (if n < 0 then 1 else 0) (__sf_l6_shl (__sf_mag_limbs n) 3) 1075 0;

// Truncation toward zero. The exponent says how far the significand sits from
// the binary point: 1075 - E bits to the right of it.
let __sf_to_int = fn (a: Sf__rv) ->
  if __sf_is_nan a || __sf_is_zero a then 0
  else
    let h = if a.exp == 0 then 0 else __sf_hidden_bit in
    let s = __sf_l6_of_limbs 0 0 (a.f3 + h) a.f2 a.f1 a.f0 in
    let sh = 1075 - __sf_eff_exp a in
    let m =
      if sh >= 0 then (if sh > 75 then __sf_l6_zero else fst (__sf_l6_shr_sticky s sh))
      else (if 0 - sh > 20 then s else __sf_l6_shl s (0 - sh)) in
    let v = __sf_l6_to_int m in
    if a.sign == 1 then 0 - v else v;
// ---- contrib/softfloat/dec.mere ----
// contrib/softfloat/dec — between a double's bits and its decimal spelling,
// in integers.
//
// The contract is the one the interpreter and the C runtime already share:
//
//   parse:  trim ASCII whitespace, drop '_', then a decimal or hex ("0x..p")
//           number, or inf / infinity / nan; the WHOLE string must be consumed;
//           too large is inf, too small is a signed zero; anything else fails
//           with:  float_of_str: "<s>" is not a valid float
//   print:  %.{p}g for p = 12..17, stopping at the first p whose output parses
//           back to the same bits; append ".0" when the result has none of
//           '.', 'e', 'E', 'n', 'i'  (so integral values print as "42.0" and
//           "inf" / "nan" / "1e+16" are left alone).
//
// Everything here is exact. A double is m * 2^e with m < 2^53, and its decimal
// expansion terminates: multiplying by 2 never lengthens the fraction, dividing
// by 2 adds at most one fraction digit. So the working value is an array of
// base-10 digits, and rounding decisions read real digits instead of guessing.
//
// The digit array is a Vec, least significant digit first, with `scale` naming
// how many of the digits are fraction digits. It is REBUILT by the two scaling
// operations rather than mutated in place -- shifting a Vec's contents to make
// room at the small end costs the same copy and earns another way to be wrong.
// Slow and right first; the day this shows up in a profile, the base can grow
// from 10 to 10^4 without changing a decision.

// ---- the digit array -------------------------------------------------------

// value(d, scale) = sum d[i] * 10^(i - scale), digits LSB first
let __sf__dc_get = fn d -> fn (i: int) ->
  if i < 0 || i >= vec_len d then 0 else vec_get d i;

// multiply by 2^k, k <= 13: carry < 2^13 and digit*2^13 + carry < 2^17, safe
// in a 32-bit int with room to spare
// IN PLACE: multiplying rewrites digits low to high and only ever APPENDS, so
// nothing needs to move. This is the hot direction -- parsing a small value
// multiplies by 2 a thousand times -- and rebuilding the array each pass made
// one parse allocate hundreds of kilobytes on a backend where a region
// reclaims nothing.
let __sf__dc_mul2k = fn d -> fn (k: int) ->
  let n = vec_len d in
  let rec go = fn (i: int) -> fn (carry: int) ->
    if i >= n && carry == 0 then ()
    else if i < n then
      let cur = (vec_get d i) * (bit_shl 1 k) + carry in
      let _ = vec_set d i (cur % 10) in
      go (i + 1) (cur / 10)
    else
      let _ = vec_push d (carry % 10) in
      go (i + 1) (carry / 10) in
  let _ = go 0 0 in
  d;

// divide by 2^k, k <= 13, extending the fraction with the exact remainder:
// at most k new fraction digits, because dividing by 2 in decimal terminates.
// Returns (digits, added) -- the caller owns the scale.
let __sf__dc_div2k = fn d -> fn (k: int) ->
  let n = vec_len d in
  let out = vec_new () in
  // the new fraction digits come from pushing the remainder below the point:
  // rem * 10 / 2^k, repeatedly, until the remainder is 0 -- k steps at most
  let rec down = fn (i: int) -> fn (rem: int) ->
    if i >= n then rem
    else
      let cur = rem * 10 + vec_get d (n - 1 - i) in
      let _ = vec_push out (cur / (bit_shl 1 k)) in     // MSB first, reversed below
      down (i + 1) (cur % (bit_shl 1 k)) in
  let rem0 = down 0 0 in
  let rec ext = fn (rem: int) -> fn (added: int) ->
    if rem == 0 then added
    else
      let cur = rem * 10 in
      let _ = vec_push out (cur / (bit_shl 1 k)) in
      ext (cur % (bit_shl 1 k)) (added + 1) in
  let added = ext rem0 0 in
  // reverse into LSB-first
  let m = vec_len out in
  let fin = vec_new () in
  let rec rev = fn (i: int) ->
    if i >= m then () else let _ = vec_push fin (vec_get out (m - 1 - i)) in rev (i + 1) in
  let _ = rev 0 in
  (fin, added);

// the highest index holding a nonzero digit, or -1 for zero
let __sf__dc_top = fn d ->
  let rec go = fn (i: int) ->
    if i < 0 then 0 - 1
    else if vec_get d i != 0 then i
    else go (i - 1) in
  go (vec_len d - 1);

// any nonzero digit strictly below index `lim`
let __sf__dc_dirty_below = fn d -> fn (lim: int) ->
  let rec go = fn (i: int) ->
    if i >= lim || i >= vec_len d then false
    else if vec_get d i != 0 then true
    else go (i + 1) in
  go 0;

// the integer part (digits at and above `scale`) as an L6 -- caller has kept it
// under 18 digits, which is under 60 bits
let __sf__dc_int_l6 = fn d -> fn (scale: int) ->
  let hi = vec_len d - 1 in
  let rec go = fn (i: int) -> fn (acc: L6__rv) ->
    if i < scale then acc
    else
      let t = __sf_l6_add (__sf_l6_shl acc 3) (__sf_l6_shl acc 1) in    // acc * 10
      go (i - 1) (__sf_l6_add t (__sf_l6_of_int (vec_get d i))) in
  go hi __sf_l6_zero;

// how many digits the integer part has (0 for a pure fraction)
let __sf__dc_intdigits = fn d -> fn (scale: int) ->
  let t = __sf__dc_top d in
  if t < scale then 0 else t - scale + 1;

// ---- decimal value -> Sf ----------------------------------------------------

// Normalise (digits, scale) * 2^0 until the integer part is EXACTLY 56 bits
// (53 + pack's three guard bits), tracking the binary exponent; then let pack
// round. The fraction that remains is sticky. Coarse steps of 13 bits while the
// integer part is clearly far away, single-bit steps for the landing.
let __sf__dc_to_sf = fn (sign: int) -> fn d0 -> fn (scale0: int) ->
  if __sf__dc_top d0 < 0 then (if sign == 1 then __sf_neg_zero else __sf_zero)
  else
    // The leading digit's decimal exponent decides the extremes outright:
    // 10^309 is already past the largest double twice over, and 10^-330 is
    // under half the smallest subnormal -- no digits can pull either back.
    // Without this, "1e1000000" walks a million-digit array to say inf.
    let x = __sf__dc_top d0 - scale0 in
    if x >= 310 then (if sign == 1 then __sf_neg_inf else __sf_inf)
    else if x <= (0 - 330) then (if sign == 1 then __sf_neg_zero else __sf_zero)
    else
    let rec norm = fn d -> fn (scale: int) -> fn (e2: int) ->
      let idig = __sf__dc_intdigits d scale in
      if idig >= 19 then
        let (nd, added) = __sf__dc_div2k d 13 in
        norm nd (scale + added) (e2 + 13)
      else if idig <= 14 then
        // 14 digits stay under 19 after * 2^13, so this cannot bounce off the
        // >= 19 arm above -- 15 would, and the two arms would hand the value
        // back and forth forever
        let nd = __sf__dc_mul2k d 13 in
        norm nd scale (e2 - 13)
      else
        let bl = __sf_l6_bitlen (__sf__dc_int_l6 d scale) in
        if bl > 56 then
          let (nd, added) = __sf__dc_div2k d 1 in
          norm nd (scale + added) (e2 + 1)
        else if bl < 56 then
          let nd = __sf__dc_mul2k d 1 in
          norm nd scale (e2 - 1)
        else (d, scale, e2) in
    let (d, scale, e2) = norm d0 scale0 0 in
    let m56 = __sf__dc_int_l6 d scale in
    let st = if __sf__dc_dirty_below d scale then 1 else 0 in
    // pack reads value = s * 2^(e - 1078); here value = m56 * 2^e2
    __sf_pack sign m56 (e2 + 1078) st;

// ---- Sf -> exact decimal ----------------------------------------------------

// the significand's decimal digits, then scaled by 2^(E - 1075) exactly
let __sf__dc_of_sf = fn (a: Sf__rv) ->
  let (sig, e) = __sf_norm_sig a in
  let d0 = vec_new () in
  let _ = vec_push d0 0 in
  // digits of sig: fold bits in, top first: d = d*2 + bit
  let rec bits = fn (i: int) -> fn d ->
    if i < 0 then d
    else
      let dd = __sf__dc_mul2k d 1 in
      let _ = (if __sf_l6_bit sig i == 1 then vec_set dd 0 (vec_get dd 0 + 1) else ()) in
      bits (i - 1) dd in
  let d1 = bits (__sf_l6_bitlen sig - 1) d0 in
  let sh = e - 1075 in
  if sh >= 0 then
    let rec up = fn d -> fn (k: int) ->
      if k == 0 then d
      else let s = (if k > 13 then 13 else k) in up (__sf__dc_mul2k d s) (k - s) in
    (up d1 sh, 0)
  else
    let rec down = fn d -> fn (scale: int) -> fn (k: int) ->
      if k == 0 then (d, scale)
      else
        let s = (if k > 13 then 13 else k) in
        let (nd, added) = __sf__dc_div2k d s in
        down nd (scale + added) (k - s) in
    down d1 0 (0 - sh);

// ---- %.{p}g ------------------------------------------------------------------

// round the digit sequence to p significant digits, half to even on the exact
// tail; returns (digits msb-first as a Vec, decimal exponent X) with the value
// d[0].d[1..] * 10^X
let __sf__dc_sigdigits = fn d -> fn (scale: int) -> fn (p: int) ->
  let top = __sf__dc_top d in
  let x0 = top - scale in
  // indices top, top-1, ... ; digit i of the output is d[top - i]
  let out = vec_new () in
  let rec take = fn (i: int) ->
    if i >= p then ()
    else let _ = vec_push out (__sf__dc_get d (top - i)) in take (i + 1) in
  let _ = take 0 in
  let nxt = __sf__dc_get d (top - p) in
  let dirty = __sf__dc_dirty_below d (top - p) in
  let roundup =
    if nxt > 5 then true
    else if nxt < 5 then false
    else if dirty then true
    else bit_and (vec_get out (p - 1)) 1 == 1 in
  if roundup then
    let rec carry = fn (i: int) ->
      if i < 0 then 1                                    // carried past the top
      else if vec_get out i == 9 then let _ = vec_set out i 0 in carry (i - 1)
      else let _ = vec_set out i (vec_get out i + 1) in 0 in
    let c = carry (p - 1) in
    if c == 1 then
      // 999.. became 1000..: one digit, then zeros
      let out2 = vec_new () in
      let _ = vec_push out2 1 in
      let rec zs = fn (i: int) -> if i >= p - 1 then () else let _ = vec_push out2 0 in zs (i + 1) in
      let _ = zs 0 in
      (out2, x0 + 1)
    else (out, x0)
  else (out, x0);

let __sf__dc_digit_ch = fn (n: int) -> chr (48 + n);

// strip trailing zeros of the significant digits (never the first digit)
let __sf__dc_lastnz = fn dig ->
  let rec go = fn (i: int) ->
    if i <= 0 then 0
    else if vec_get dig i != 0 then i
    else go (i - 1) in
  go (vec_len dig - 1);

let __sf__dc_fmt_exp = fn (x: int) ->
  let mag = if x < 0 then 0 - x else x in
  let body = str_of_int mag in
  "e" ++ (if x < 0 then "-" else "+") ++ (if mag < 10 then "0" ++ body else body);

// %.{p}g of a nonzero finite value whose exact digits are (d, scale)
let __sf__dc_g = fn (sign: int) -> fn d -> fn (scale: int) -> fn (p: int) ->
  let (dig, x) = __sf__dc_sigdigits d scale p in
  let last = __sf__dc_lastnz dig in
  let s0 =
    if x < (0 - 4) || x >= p then
      // exponent form: d[.ddd]e±XX
      let rec frac = fn (i: int) -> fn (acc: str) ->
        if i > last then acc else frac (i + 1) (acc ++ __sf__dc_digit_ch (vec_get dig i)) in
      __sf__dc_digit_ch (vec_get dig 0)
        ++ (if last >= 1 then "." ++ frac 1 "" else "")
        ++ __sf__dc_fmt_exp x
    else if x >= 0 then
      // ddd[.ddd] -- the point sits after digit x
      let rec go = fn (i: int) -> fn (acc: str) ->
        if i > last && i > x then acc
        else
          let acc2 = (if i == x + 1 then acc ++ "." else acc) in
          go (i + 1) (acc2 ++ __sf__dc_digit_ch (if i <= last then vec_get dig i else 0)) in
      go 0 ""
    else
      // 0.00ddd -- (-x - 1) zeros between the point and the first digit
      let rec zs = fn (i: int) -> fn (acc: str) ->
        if i >= (0 - x) - 1 then acc else zs (i + 1) (acc ++ "0") in
      let rec go = fn (i: int) -> fn (acc: str) ->
        if i > last then acc else go (i + 1) (acc ++ __sf__dc_digit_ch (vec_get dig i)) in
      "0." ++ zs 0 "" ++ go 0 "" in
  (if sign == 1 then "-" else "") ++ s0;

// ---- the parser --------------------------------------------------------------

let __sf__dc_is_ws = fn (c: str) ->
  str_eq c " " || str_eq c "\t" || str_eq c "\n" || str_eq c "\r" || str_eq c "\012";

let __sf__dc_digit = fn (c: str) ->
  let n = ord c in
  if n >= 48 && n <= 57 then n - 48 else 0 - 1;

let __sf__dc_hexdigit = fn (c: str) ->
  let n = ord c in
  if n >= 48 && n <= 57 then n - 48
  else if n >= 97 && n <= 102 then n - 87
  else if n >= 65 && n <= 70 then n - 55
  else 0 - 1;

// trim + drop underscores, in one pass over the raw string
let __sf__dc_clean = fn (s: str) ->
  let n = str_len s in
  let rec lead = fn (i: int) -> if i < n && __sf__dc_is_ws (char_at s i) then lead (i + 1) else i in
  let rec trail = fn (i: int) -> if i > 0 && __sf__dc_is_ws (char_at s (i - 1)) then trail (i - 1) else i in
  let a = lead 0 in
  let b = trail n in
  let rec go = fn (i: int) -> fn (acc: str) ->
    if i >= b then acc
    else
      let c = char_at s i in
      go (i + 1) (if str_eq c "_" then acc else acc ++ c) in
  go a "";

// hex: 0x H [. H] [p±d] -- mantissa bits are the digits, the exponent is a
// power of two, so this never needs the decimal machinery: collect up to 56
// bits, everything further is sticky, and pack does the rest.
let __sf__dc_parse_hex = fn (sign: int) -> fn (t: str) -> fn (fail_s: str) ->
  let n = str_len t in
  let rec mant = fn (i: int) -> fn (acc: L6__rv) -> fn (bits: int) -> fn (st: int) ->
                 fn (fdig: int) -> fn (seen: int) -> fn (dot: int) ->
    if i >= n then (i, acc, bits, st, fdig, seen, dot)
    else
      let c = char_at t i in
      if str_eq c "." && dot == 0 then mant (i + 1) acc bits st fdig seen 1
      else
        let h = __sf__dc_hexdigit c in
        if h < 0 then (i, acc, bits, st, fdig, seen, dot)
        else
          let fd = fdig + (if dot == 1 then 1 else 0) in
          if bits >= 57 then
            // No more room: the digit is sticky. An INTEGER digit skipped here
            // still scales the value by 16, which is fdig - 1 in the exponent
            // pexp - 4*fdig; a FRACTION digit skipped here scales nothing.
            mant (i + 1) acc bits (bit_or st (if h != 0 then 1 else 0))
                 (fdig + (if dot == 1 then 0 else 0 - 1)) seen dot
          else
            mant (i + 1) (__sf_l6_add (__sf_l6_shl acc 4) (__sf_l6_of_int h))
                 (if bits == 0 && h == 0 then 0 else __sf_l6_bitlen (__sf_l6_add (__sf_l6_shl acc 4) (__sf_l6_of_int h)))
                 st fd (seen + 1) dot in
  let (i1, m, _, st, fdig, seen, _) = mant 0 __sf_l6_zero 0 0 0 0 0 in
  if seen == 0 then fail fail_s else
  let (i2, pexp) =
    if i1 < n && (str_eq (char_at t i1) "p" || str_eq (char_at t i1) "P") then
      let rec pe = fn (i: int) -> fn (acc: int) -> fn (any: int) -> fn (psign: int) ->
        if i >= n then (if any == 0 then (0 - 1, 0) else (i, psign * acc))
        else
          let c = char_at t i in
          if any == 0 && str_eq c "-" then pe (i + 1) acc 0 (0 - 1)
          else if any == 0 && str_eq c "+" then pe (i + 1) acc 0 psign
          else
            let dg = __sf__dc_digit c in
            if dg < 0 then (if any == 0 then (0 - 1, 0) else (i, psign * acc))
            else pe (i + 1) (if acc > 100000 then acc else acc * 10 + dg) (any + 1) psign in
      pe (i1 + 1) 0 0 1
    else (i1, 0) in
  if i2 != n || i2 < 0 then fail fail_s else
  if __sf_l6_is_zero m && st == 0 then (if sign == 1 then __sf_neg_zero else __sf_zero) else
  // value = m * 2^(pexp - 4*fdig); normalise m to 56 bits for pack
  let rec up = fn (v: L6__rv) -> fn (e: int) ->
    if __sf_l6_bitlen v >= 56 then (v, e) else up (__sf_l6_shl v 1) (e - 1) in
  let rec dn = fn (v: L6__rv) -> fn (e: int) -> fn (stx: int) ->
    if __sf_l6_bitlen v <= 56 then (v, e, stx)
    else let pr = __sf_l6_shr_sticky v 1 in dn (fst pr) (e + 1) (bit_or stx (snd pr)) in
  let (m1, e1) = up m (pexp - 4 * fdig) in
  let (m2, e2, st2) = dn m1 e1 st in
  __sf_pack sign m2 (e2 + 1078) st2;

// decimal or hex or the named specials; the whole string or nothing
let __sf_sf_of_dec = fn (s: str) ->
  let fail_s = "float_of_str: \"" ++ s ++ "\" is not a valid float" in
  let t0 = __sf__dc_clean s in
  let (sign, t) =
    if str_len t0 > 0 && str_eq (char_at t0 0) "-" then (1, substring t0 1 (str_len t0))
    else if str_len t0 > 0 && str_eq (char_at t0 0) "+" then (0, substring t0 1 (str_len t0))
    else (0, t0) in
  if str_eq t "inf" || str_eq t "infinity" then (if sign == 1 then __sf_neg_inf else __sf_inf)
  else if str_eq t "nan" then __sf_nan
  else if str_len t >= 2 && str_eq (substring t 0 2) "0x" || str_len t >= 2 && str_eq (substring t 0 2) "0X" then
    __sf__dc_parse_hex sign (substring t 2 (str_len t)) fail_s
  else
    let n = str_len t in
    // digits [. digits] [e±d]; at least one digit somewhere before the e
    let d = vec_new () in                                // MSB first while reading
    let rec mant = fn (i: int) -> fn (fdig: int) -> fn (seen: int) -> fn (dot: int) ->
      if i >= n then (i, fdig, seen)
      else
        let c = char_at t i in
        if str_eq c "." && dot == 0 then mant (i + 1) fdig seen 1
        else
          let dg = __sf__dc_digit c in
          if dg < 0 then (i, fdig, seen)
          else
            let _ = vec_push d dg in
            mant (i + 1) (fdig + (if dot == 1 then 1 else 0)) (seen + 1) dot in
    let (i1, fdig, seen) = mant 0 0 0 0 in
    if seen == 0 then fail fail_s else
    let (i2, dexp) =
      if i1 < n && (str_eq (char_at t i1) "e" || str_eq (char_at t i1) "E") then
        let rec pe = fn (i: int) -> fn (acc: int) -> fn (any: int) -> fn (psign: int) ->
          if i >= n then (if any == 0 then (0 - 1, 0) else (i, psign * acc))
          else
            let c = char_at t i in
            if any == 0 && str_eq c "-" then pe (i + 1) acc 0 (0 - 1)
            else if any == 0 && str_eq c "+" then pe (i + 1) acc 0 psign
            else
              let dg = __sf__dc_digit c in
              if dg < 0 then (if any == 0 then (0 - 1, 0) else (i, psign * acc))
              // the exponent saturates: past |10^6| the value is decided by the
              // digit count alone, and 10^6 digits is not a real input
              else pe (i + 1) (if acc > 1000000 then acc else acc * 10 + dg) (any + 1) psign in
        pe (i1 + 1) 0 0 1
      else (i1, 0) in
    if i2 != n || i2 < 0 then fail fail_s else
    // value = digits * 10^(dexp - fdig): LSB-first array, scale from the point
    let m = vec_len d in
    let lsb = vec_new () in
    let rec rev = fn (i: int) ->
      if i >= m then () else let _ = vec_push lsb (vec_get d (m - 1 - i)) in rev (i + 1) in
    let _ = rev 0 in
    let k = dexp - fdig in
    let topnz = __sf__dc_top lsb in
    if topnz < 0 then (if sign == 1 then __sf_neg_zero else __sf_zero)
    else if topnz + k >= 310 then (if sign == 1 then __sf_neg_inf else __sf_inf)
    else if topnz + k <= (0 - 330) then (if sign == 1 then __sf_neg_zero else __sf_zero)
    // fold 10^k in: k > 0 appends zeros at the LSB end; k < 0 raises the scale
    else if k >= 0 then
      let shifted = vec_new () in
      let rec zs = fn (i: int) -> if i >= k then () else let _ = vec_push shifted 0 in zs (i + 1) in
      let _ = zs 0 in
      let rec cp = fn (i: int) -> if i >= m then () else let _ = vec_push shifted (vec_get lsb i) in cp (i + 1) in
      let _ = cp 0 in
      __sf__dc_to_sf sign shifted 0
    else
      __sf__dc_to_sf sign lsb (0 - k);

