  // does, checked rather than assumed (test/float/softfloat_add.mere).
  // A SIGNALLING NaN outranks a quiet one, whichever side it is on: the answer
  // is the signalling one, quieted. Among quiet NaNs the first operand wins.
  // Both halves of that were measured, not assumed -- the second half cost a
  // gate failure on `quiet + signalling`, where returning the first NaN gave
  // the wrong 64 bits.
  if __sf_is_snan a then __sf_quiet a
  else if __sf_is_snan b then __sf_quiet b
  else if __sf_is_nan a then __sf_quiet a
  else if __sf_is_nan b then __sf_quiet b
  else if __sf_is_inf a then
    (if __sf_is_inf b && a.sign != b.sign then __sf_nan else a)
  else if __sf_is_inf b then b
  else if __sf_is_zero a && __sf_is_zero b then
    // +0 + -0 is +0 under round-to-nearest; only two negative zeros give one
    (if a.sign == 1 && b.sign == 1 then __sf_neg_zero else __sf_zero)
  else if __sf_is_zero a then b
  else if __sf_is_zero b then a
  else
    let ea = __sf_eff_exp a in let eb = __sf_eff_exp b in
    let sa = __sf_sig_of a in let sb = __sf_sig_of b in
    // order by magnitude so the subtraction below never goes negative
    let a_first =
      if ea != eb then ea > eb else __sf_l6_cmp sa sb >= 0 in
    let hs = if a_first then a.sign else b.sign in
    let ls = if a_first then b.sign else a.sign in
    let he = if a_first then ea else eb in
    let __sf_le = if a_first then eb else ea in
    let hv = if a_first then sa else sb in
    let lv = if a_first then sb else sa in
    let d = he - __sf_le in
    // Past 60 the whole of the smaller value is below the sticky, and shifting
    // one bit at a time that far is only slow.
    let (lv2, st) = if d > 60 then (__sf_l6_zero, if __sf_l6_is_zero lv then 0 else 1)
                    else __sf_l6_shr_sticky lv d in
    if hs == ls then __sf_pack hs (__sf_l6_add hv lv2) he st
    else
      // a - (b + f) with 0 < f < 1 is (a - b - 1) + (1 - f): borrow one and
      // keep the sticky set, because the remainder is not zero
      let diff = if st == 1 then __sf_l6_sub (__sf_l6_sub hv lv2) __sf_l6_one else __sf_l6_sub hv lv2 in
      if __sf_l6_is_zero diff && st == 0 then __sf_zero    // exact cancellation is +0
      else __sf_pack hs diff he st;

