#!/usr/bin/env python3
"""Generate the benchmark inputs.

The inputs are GENERATED rather than committed, for the same reason the
Unicode tables are: a multi-megabyte blob in the tree is a blob nobody
reviews. They are generated by an LCG with a fixed seed, so the same file
comes out on every machine and every run -- which is what lets the
same-answer check below be an equality and not a tolerance.

Python is the generator on purpose. Generating the input with Mere would
close a loop: a bug in Mere would change the input, and every
implementation would then agree on the wrong bytes while the comparison
looked healthy.

Sizes are the smallest that put the measured work above process startup on
a 2020s laptop; see benchmarks/README.md for why that floor matters.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")

# One LCG for every input (glibc's constants), so "the input" is a few lines
# a reader can re-derive rather than a file they have to trust.
MASK = (1 << 31) - 1


def lcg(seed):
    x = seed
    while True:
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        yield x


def gen_bytes(path, n):
    """crc32's input: n bytes with no structure at all."""
    g = lcg(20260824)
    buf = bytearray(n)
    for i in range(n):
        buf[i] = (next(g) >> 16) & 0xFF
    with open(path, "wb") as f:
        f.write(buf)
    return n


def gen_words(path, n_words):
    """wordfreq's input: a Zipf-ish stream over a synthetic vocabulary.

    Zipf-ish and not uniform because a uniform stream makes every count
    equal, and a top-N ranking over equal counts is decided entirely by the
    tie-break -- the implementations would then be compared on their sort
    stability rather than on their counting.
    """
    vocab = ["w%04d" % i for i in range(5000)]
    g = lcg(770707)
    out = []
    line = []
    for i in range(n_words):
        # rank = floor(V**r) with r uniform: log-uniform over ranks, which is
        # Zipf's 1/k. The first shape tried here was V/(1+rV), and it put half
        # of all 300k occurrences on ONE word and touched 885 of the 5000 --
        # a hash table that small stops being part of what is measured.
        r = next(g) / float(MASK)
        rank = int(len(vocab) ** r) - 1
        if rank >= len(vocab):
            rank = len(vocab) - 1
        if rank < 0:
            rank = 0
        line.append(vocab[rank])
        if len(line) == 12:
            out.append(" ".join(line))
            line = []
    if line:
        out.append(" ".join(line))
    text = "\n".join(out) + "\n"
    with open(path, "w") as f:
        f.write(text)
    return len(text)


def main():
    os.makedirs(DATA, exist_ok=True)
    b = os.path.join(DATA, "bytes.bin")
    w = os.path.join(DATA, "words.txt")
    force = "--force" in sys.argv

    if force or not os.path.exists(b):
        n = gen_bytes(b, 4 * 1024 * 1024)
        print("generated %s (%d bytes)" % (b, n))
    else:
        print("kept %s" % b)

    if force or not os.path.exists(w):
        n = gen_words(w, 300000)
        print("generated %s (%d bytes)" % (w, n))
    else:
        print("kept %s" % w)


if __name__ == "__main__":
    main()
